import { ResumeData, SCHEMA_VERSION, SectionKey } from '../types/resume';

export interface ValidationResult {
  isValid: boolean;
  error?: string;
  data?: ResumeData;
}

const VALID_SECTION_KEYS: SectionKey[] = [
  'summary',
  'experience',
  'projects',
  'education',
  'skills',
  'certifications',
  'achievements'
];

export function validateResumeData(json: unknown): ValidationResult {
  if (!json || typeof json !== 'object') {
    return { isValid: false, error: 'Uploaded file is not a valid JSON object.' };
  }

  const candidate = json as Partial<ResumeData>;

  // Schema version check
  if (!candidate.schemaVersion) {
    return {
      isValid: false,
      error: 'Missing "schemaVersion" field. Please ensure the file was generated by CareerCraft Studio.'
    };
  }

  const [candidateMajor] = String(candidate.schemaVersion).split('.');
  const [currentMajor] = SCHEMA_VERSION.split('.');
  if (candidateMajor !== currentMajor) {
    return {
      isValid: false,
      error: `Unsupported schema version (${candidate.schemaVersion}). This tool expects version ${SCHEMA_VERSION}.`
    };
  }

  // Profile check
  if (!candidate.profile || typeof candidate.profile !== 'object') {
    return { isValid: false, error: 'Resume file is missing the required "profile" section.' };
  }

  if (typeof candidate.profile.fullName !== 'string') {
    return { isValid: false, error: 'Profile must contain a "fullName" text property.' };
  }

  // Arrays checks
  const ensureArray = (val: unknown): boolean => Array.isArray(val);

  if (candidate.experience && !ensureArray(candidate.experience)) {
    return { isValid: false, error: '"experience" must be a list of work history entries.' };
  }
  if (candidate.education && !ensureArray(candidate.education)) {
    return { isValid: false, error: '"education" must be a list of education entries.' };
  }
  if (candidate.projects && !ensureArray(candidate.projects)) {
    return { isValid: false, error: '"projects" must be a list of project items.' };
  }
  if (candidate.skills && !ensureArray(candidate.skills)) {
    return { isValid: false, error: '"skills" must be a list of skill items.' };
  }
  if (candidate.certifications && !ensureArray(candidate.certifications)) {
    return { isValid: false, error: '"certifications" must be a list of certifications.' };
  }
  if (candidate.achievements && !ensureArray(candidate.achievements)) {
    return { isValid: false, error: '"achievements" must be a list of achievements.' };
  }

  // Settings sanitization
  const settings = candidate.settings || {
    selectedTemplate: 'modern',
    sectionOrder: [...VALID_SECTION_KEYS],
    hiddenSections: [],
    accentColor: '#4f46e5',
    fontFamily: 'sans',
    fontSize: 'normal',
    spacing: 'normal'
  };

  // Ensure section order contains all valid sections
  const existingOrder = Array.isArray(settings.sectionOrder)
    ? settings.sectionOrder.filter((k): k is SectionKey => VALID_SECTION_KEYS.includes(k as SectionKey))
    : [];
  
  // Append any missing keys
  const completeOrder: SectionKey[] = [...existingOrder];
  for (const k of VALID_SECTION_KEYS) {
    if (!completeOrder.includes(k)) {
      completeOrder.push(k);
    }
  }

  const validTemplates = ['classic', 'modern', 'minimal'];
  const sanitizedTemplate = validTemplates.includes(settings.selectedTemplate)
    ? settings.selectedTemplate
    : 'modern';

  const cleanData: ResumeData = {
    schemaVersion: SCHEMA_VERSION,
    profile: {
      fullName: candidate.profile.fullName || '',
      professionalTitle: candidate.profile.professionalTitle || '',
      email: candidate.profile.email || '',
      phone: candidate.profile.phone || '',
      location: candidate.profile.location || '',
      portfolioUrl: candidate.profile.portfolioUrl || '',
      linkedInUrl: candidate.profile.linkedInUrl || ''
    },
    summary: typeof candidate.summary === 'string' ? candidate.summary : '',
    experience: Array.isArray(candidate.experience) ? candidate.experience : [],
    education: Array.isArray(candidate.education) ? candidate.education : [],
    projects: Array.isArray(candidate.projects) ? candidate.projects : [],
    skills: Array.isArray(candidate.skills) ? candidate.skills : [],
    certifications: Array.isArray(candidate.certifications) ? candidate.certifications : [],
    achievements: Array.isArray(candidate.achievements) ? candidate.achievements : [],
    settings: {
      selectedTemplate: sanitizedTemplate,
      sectionOrder: completeOrder,
      hiddenSections: Array.isArray(settings.hiddenSections) ? settings.hiddenSections : [],
      accentColor: settings.accentColor || '#4f46e5',
      fontFamily: settings.fontFamily || 'sans',
      fontSize: settings.fontSize || 'normal',
      spacing: settings.spacing || 'normal'
    }
  };

  return { isValid: true, data: cleanData };
}
